#!/usr/bin/env python3
"""Check the original Issue495 targets and precisely reviewed legacy references."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL_SKILLS = (
    "cot-contrarian-detector",
    "dividend-growth-pullback-screener",
    "downtrend-duration-analyzer",
    "earnings-calendar",
    "economic-calendar-fetcher",
    "institutional-flow-tracker",
    "kanchi-dividend-sop",
    "news-reaction-failure-analyzer",
    "options-strategy-advisor",
    "pair-trade-screener",
    "signal-postmortem",
    "stockbee-20pct-study",
    "stockbee-episodic-pivot-analyzer",
    "stockbee-exhaustion-hammer-screener",
    "stockbee-momentum-burst-screener",
    "stockbee-setup-fluency-trainer",
    "technical-analyst",
    "theme-detector",
    "trader-memory-core",
    "value-dividend-screener",
)
LEGACY_FRAGMENT = "api/v3"
MANIFEST = "docs/dev/fmp-legacy-exceptions.json"


def generated_paths(configs):
    """The exact registry output paths, including generated compatibility shims."""
    paths = set()
    for name, cfg in configs.items():
        paths.add(f"skills/{name}/scripts/fmp_client.py")
        if cfg.has_compat:
            paths.add(f"skills/{name}/scripts/_fmp_compat.py")
    return paths


def audit(root, configs, exceptions):
    errors = []
    for name in ORIGINAL_SKILLS:
        if name not in configs:
            errors.append(f"{name}: original target is not registered")
        client = root / "skills" / name / "scripts/fmp_client.py"
        if not client.is_file():
            errors.append(f"{name}: generated client missing")
        elif "# GENERATED by scripts/generate_fmp_client.py" not in client.read_text():
            errors.append(f"{name}: client has no generator ownership marker")
        directory = root / "skills" / name / "scripts"
        consumers = [
            p for p in directory.glob("*.py") if p.name not in {"fmp_client.py", "_fmp_compat.py"}
        ]
        if not any("fmp_client" in p.read_text() for p in consumers):
            errors.append(f"{name}: no runtime generated-client delegation reference")

    allowed = {}
    for entry in exceptions:
        if not isinstance(entry, dict):
            errors.append("invalid exception object")
            continue
        path, line, reason = (entry.get(k) for k in ("path", "line", "reason"))
        if not all(isinstance(v, str) and v.strip() for v in (path, line, reason)):
            errors.append("exception needs exact path, line and nonempty reason")
            continue
        if path.startswith("/") or ".." in Path(path).parts or any(c in path for c in "*?[]"):
            errors.append("exception path must be exact and relative")
            continue
        if LEGACY_FRAGMENT not in line or line == LEGACY_FRAGMENT:
            errors.append(f"{path}: exception must pin the complete legacy-reference line")
            continue
        key = (path, line.strip())
        if key in allowed:
            errors.append(f"{path}: duplicate exception")
        allowed[key] = 0

    generated = generated_paths(configs)
    for folder in ("skills", "scripts", "examples"):
        for path in sorted((root / folder).rglob("*.py")):
            relative = path.relative_to(root).as_posix()
            if "tests" in path.relative_to(root).parts or relative in generated:
                continue
            for number, line in enumerate(path.read_text().splitlines(), 1):
                if LEGACY_FRAGMENT not in line:
                    continue
                key = (relative, line.strip())
                if key in allowed:
                    allowed[key] += 1
                else:
                    errors.append(f"{relative}:{number}: unreviewed legacy reference")
    for (path, _), count in allowed.items():
        if count != 1:
            errors.append(f"{path}: stale or duplicated exception (matched {count} lines)")
    return errors


def audit_repository(root=ROOT):
    # Import through the repository package when executed directly as a script.
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from scripts.generate_fmp_client import _load_registry

    manifest = json.loads((root / MANIFEST).read_text())
    if manifest.get("original_skills") != list(ORIGINAL_SKILLS):
        return ["manifest must retain the exact original 20-skill inventory"]
    return audit(root, _load_registry(), manifest["exceptions"])


def main():
    errors = audit_repository()
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1
    print("OK: original 20 FMP targets registered; legacy references precisely accounted for")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
