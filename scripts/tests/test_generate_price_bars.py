"""Tests for scripts/generate_price_bars.py (issue #655)."""

from __future__ import annotations

import importlib.util
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]


def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def generator():
    return _load(REPO_ROOT / "scripts" / "generate_price_bars.py", "price_bars_gen")


@pytest.fixture
def fake_root(tmp_path):
    shutil.copytree(REPO_ROOT / "scripts" / "price_bars", tmp_path / "scripts" / "price_bars")
    (tmp_path / "config").mkdir()
    (tmp_path / "config" / "price-bars-consumers.yaml").write_text(
        "- demo-skill\n", encoding="utf-8"
    )
    (tmp_path / "skills" / "demo-skill" / "scripts").mkdir(parents=True)
    (tmp_path / "skills" / "other-skill" / "scripts").mkdir(parents=True)
    return tmp_path


def _run(generator, root: Path, *extra: str) -> int:
    return generator.main(["--root", str(root), *extra])


def test_repository_check_passes(generator):
    assert generator.main(["--check"]) == 0


def test_repository_consumers_start_with_ftd_detector(generator):
    consumers = generator.load_consumers(REPO_ROOT)
    assert consumers[0] == "ftd-detector"


def test_targets_are_banner_plus_source(generator):
    rendered = dict(generator.targets(REPO_ROOT, ["ftd-detector"]))
    module = REPO_ROOT / "skills" / "ftd-detector" / "scripts" / "_price_bars.py"
    contract = (
        REPO_ROOT / "skills" / "ftd-detector" / "scripts" / "tests" / "test_price_bars_contract.py"
    )
    assert set(rendered) == {module, contract}
    source = (REPO_ROOT / "scripts" / "price_bars" / "price_bars.py").read_text(encoding="utf-8")
    assert rendered[module] == generator.BANNER + source
    assert rendered[module].startswith("# GENERATED by scripts/generate_price_bars.py")


def test_write_then_check_passes(generator, fake_root):
    assert _run(generator, fake_root, "--check") == 1  # nothing generated yet
    assert _run(generator, fake_root) == 0
    assert (fake_root / "skills" / "demo-skill" / "scripts" / "_price_bars.py").is_file()
    assert _run(generator, fake_root, "--check") == 0


def test_drift_fails_check_without_writing(generator, fake_root, capsys):
    assert _run(generator, fake_root) == 0
    target = fake_root / "skills" / "demo-skill" / "scripts" / "_price_bars.py"
    target.write_text(target.read_text(encoding="utf-8") + "# edited\n", encoding="utf-8")
    assert _run(generator, fake_root, "--check") == 1
    assert "DRIFT: skills/demo-skill/scripts/_price_bars.py" in capsys.readouterr().err
    assert target.read_text(encoding="utf-8").endswith("# edited\n")
    assert _run(generator, fake_root) == 0
    assert _run(generator, fake_root, "--check") == 0


@pytest.mark.parametrize(
    "relative", ["scripts/_price_bars.py", "scripts/tests/test_price_bars_contract.py"]
)
def test_stray_file_in_non_consumer_fails_check(generator, fake_root, capsys, relative):
    assert _run(generator, fake_root) == 0
    stray = fake_root / "skills" / "other-skill" / relative
    stray.parent.mkdir(parents=True, exist_ok=True)
    stray.write_text("# stray\n", encoding="utf-8")
    assert _run(generator, fake_root, "--check") == 1
    assert f"STRAY: skills/other-skill/{relative}" in capsys.readouterr().err
    # write mode never deletes; it still reports the stray file
    assert _run(generator, fake_root) == 1
    assert stray.is_file()


@pytest.mark.parametrize(
    "relative",
    [
        "skills/demo-skill/scripts/vendor/_price_bars.py",  # nested, even in a consumer
        "skills/other-skill/scripts/lib/deep/test_price_bars_contract.py",
        "skills/other-skill/_price_bars.py",
        "examples/weekly/skills/demo-skill/scripts/_price_bars.py",
    ],
)
def test_nested_or_example_copy_fails_check(generator, fake_root, capsys, relative):
    assert _run(generator, fake_root) == 0
    stray = fake_root / relative
    stray.parent.mkdir(parents=True, exist_ok=True)
    stray.write_text("# stray\n", encoding="utf-8")
    assert _run(generator, fake_root, "--check") == 1
    assert f"STRAY: {relative}" in capsys.readouterr().err


@pytest.mark.parametrize(
    "content,message",
    [
        ("{}\n", "non-empty list"),
        ("[]\n", "non-empty list"),
        ("- demo-skill\n- demo-skill\n", "unique"),
        ("- missing-skill\n", "no skills/missing-skill/scripts"),
        ("- 3\n", "non-empty list"),
    ],
)
def test_invalid_consumer_config_is_rejected(generator, fake_root, content, message):
    (fake_root / "config" / "price-bars-consumers.yaml").write_text(content, encoding="utf-8")
    with pytest.raises(ValueError, match=message):
        generator.load_consumers(fake_root)


def test_generated_contract_test_passes(generator, fake_root):
    assert _run(generator, fake_root) == 0
    scripts_dir = fake_root / "skills" / "demo-skill" / "scripts"
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "-q",
            "-p",
            "no:cacheprovider",
            str(scripts_dir / "tests" / "test_price_bars_contract.py"),
        ],
        cwd=fake_root,
        env={"PYTHONPATH": str(scripts_dir), "PATH": "/usr/bin:/bin"},
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "passed" in result.stdout
