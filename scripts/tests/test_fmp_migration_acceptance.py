"""The final Issue495 gate rejects missing targets and unreviewed legacy refs."""

import importlib
from types import SimpleNamespace


def gate():
    return importlib.import_module("scripts.check_fmp_migration")


def fixture_root(tmp_path):
    mod = gate()
    configs = {name: SimpleNamespace(has_compat=False) for name in mod.ORIGINAL_SKILLS}
    for name in configs:
        path = tmp_path / "skills" / name / "scripts/fmp_client.py"
        path.parent.mkdir(parents=True)
        path.write_text('# GENERATED by scripts/generate_fmp_client.py\nURL="api/v3"\n')
        (path.parent / "consumer.py").write_text("from fmp_client import FMPClient\n")
    return mod, configs


def test_repository_acceptance_manifest_is_complete():
    mod = gate()
    assert not mod.audit_repository(mod.ROOT)


def test_twenty_targets_and_exact_generated_exclusion(tmp_path):
    mod, configs = fixture_root(tmp_path)
    assert not mod.audit(tmp_path, configs, [])
    configs.pop(next(iter(configs)))
    assert any("registered" in error for error in mod.audit(tmp_path, configs, []))


def test_missing_client_is_not_covered_by_exception(tmp_path):
    mod, configs = fixture_root(tmp_path)
    name = mod.ORIGINAL_SKILLS[0]
    (tmp_path / "skills" / name / "scripts/fmp_client.py").unlink()
    assert any("client" in error for error in mod.audit(tmp_path, configs, []))


def test_hidden_snapshot_legacy_needs_exact_reasoned_exception(tmp_path):
    mod, configs = fixture_root(tmp_path)
    relative = "examples/demo/.claude/skills/old/script.py"
    path = tmp_path / relative
    path.parent.mkdir(parents=True)
    line = 'URL="https://provider.invalid/api/v3"'
    path.write_text(line + "\n")
    assert any(relative in error for error in mod.audit(tmp_path, configs, []))
    entry = {
        "path": relative,
        "line": line,
        "reason": "Historical snapshot; not the installed canonical skill.",
    }
    assert not mod.audit(tmp_path, configs, [entry])
    for bad in [
        dict(entry, reason=""),
        dict(entry, path="examples/**"),
        dict(entry, line="api/v3"),
    ]:
        assert mod.audit(tmp_path, configs, [bad])
    path.write_text('URL="stable"\n')
    assert any("stale" in error for error in mod.audit(tmp_path, configs, [entry]))


def test_unregistered_fmp_client_name_cannot_hide_legacy(tmp_path):
    mod, configs = fixture_root(tmp_path)
    path = tmp_path / "skills/unregistered/scripts/fmp_client.py"
    path.parent.mkdir(parents=True)
    path.write_text('URL="api/v3"\n')
    assert mod.audit(tmp_path, configs, [])


def test_compat_exclusion_comes_from_registry(tmp_path):
    mod, configs = fixture_root(tmp_path)
    name = mod.ORIGINAL_SKILLS[0]
    path = tmp_path / "skills" / name / "scripts/_fmp_compat.py"
    path.write_text('URL="api/v3"\n')
    assert mod.audit(tmp_path, configs, [])
    configs[name].has_compat = True
    assert not mod.audit(tmp_path, configs, [])
