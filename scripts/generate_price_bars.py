#!/usr/bin/env python3
"""Generate and validate the vendored price-bar helper (issue #655).

Source of truth: ``scripts/price_bars/price_bars.py`` and the contract-test
template next to it. Consumers are listed in ``config/price-bars-consumers.yaml``.
Each consumer gets ``scripts/_price_bars.py`` and
``scripts/tests/test_price_bars_contract.py``, both prefixed with a GENERATED
banner. ``--check`` fails on drift and on a stray copy in a non-consumer skill.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_RELATIVE = Path("config") / "price-bars-consumers.yaml"
SOURCE_RELATIVE = Path("scripts") / "price_bars" / "price_bars.py"
TEMPLATE_RELATIVE = Path("scripts") / "price_bars" / "test_price_bars_contract.py.tmpl"
MODULE_NAME = "_price_bars.py"
CONTRACT_NAME = "test_price_bars_contract.py"
BANNER = (
    "# GENERATED by scripts/generate_price_bars.py — do not edit.\n"
    "# Source of truth: scripts/price_bars/ and config/price-bars-consumers.yaml.\n"
)


def load_consumers(root: Path = REPO_ROOT) -> list[str]:
    data = yaml.safe_load((root / CONFIG_RELATIVE).read_text(encoding="utf-8"))
    if (
        not isinstance(data, list)
        or not data
        or not all(isinstance(item, str) and item for item in data)
    ):
        raise ValueError(f"{CONFIG_RELATIVE} must be a non-empty list of skill ids")
    if len(data) != len(set(data)):
        raise ValueError(f"{CONFIG_RELATIVE} consumers must be unique")
    for skill in data:
        if not (root / "skills" / skill / "scripts").is_dir():
            raise ValueError(f"{CONFIG_RELATIVE}: no skills/{skill}/scripts directory")
    return data


def targets(root: Path, consumers: list[str]) -> list[tuple[Path, str]]:
    module = BANNER + (root / SOURCE_RELATIVE).read_text(encoding="utf-8")
    tests = BANNER + (root / TEMPLATE_RELATIVE).read_text(encoding="utf-8")
    rendered: list[tuple[Path, str]] = []
    for skill in consumers:
        scripts_dir = root / "skills" / skill / "scripts"
        rendered.append((scripts_dir / MODULE_NAME, module))
        rendered.append((scripts_dir / "tests" / CONTRACT_NAME, tests))
    return rendered


STRAY_SEARCH_DIRS = ("skills", "examples")


def stray_files(root: Path, consumers: list[str]) -> list[Path]:
    """Copies of the generated files anywhere under skills/ or examples/
    (at any depth) other than the expected consumer paths."""
    expected = {path for path, _ in targets(root, consumers)}
    found: set[Path] = set()
    for top in STRAY_SEARCH_DIRS:
        base = root / top
        if not base.is_dir():
            continue
        for name in (MODULE_NAME, CONTRACT_NAME):
            found.update(path for path in base.rglob(name) if path.is_file())
    return sorted(found - expected)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="Fail when a target drifts")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    consumers = load_consumers(root)
    failed = False
    for path, content in targets(root, consumers):
        relative = path.relative_to(root).as_posix()
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if args.check:
            if current != content:
                print(f"DRIFT: {relative}", file=sys.stderr)
                failed = True
            else:
                print(f"OK: {relative}", file=sys.stderr)
        elif current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {relative}", file=sys.stderr)
        else:
            print(f"Unchanged {relative}", file=sys.stderr)
    for path in stray_files(root, consumers):
        relative = path.relative_to(root).as_posix()
        print(
            f"STRAY: {relative} (skill is not in {CONFIG_RELATIVE.as_posix()}; "
            "add it there or delete the file)",
            file=sys.stderr,
        )
        failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
